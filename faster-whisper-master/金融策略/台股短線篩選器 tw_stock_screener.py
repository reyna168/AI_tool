def symbol_to_yf(symbol: str) -> str:
    """將台股代號轉為 yfinance 格式（上市 .TW / 上櫃 .TWO）"""
    symbol = symbol.strip()
    # 上市股票代號通常為 4 碼數字，上櫃股票代號範圍較廣
    # 簡易判斷：若代號在常見上櫃範圍則用 .TWO，否則用 .TW
    # 注意：此判斷不完美，建議在 watchlist.csv 中直接標註
    try:
        code = int(symbol)
    except ValueError:
        return symbol  # 已含後綴則直接回傳

    # 常見上櫃代號區間（非完整列表，使用者可自行調整）
    otc_ranges = [
        (4100, 4999),  # 電子上櫃
        (5200, 5999),  # 電子上櫃
        (6100, 6999),  # 電子上櫃
        (7400, 7499),  # 其他
        (8000, 8999),  # 其他上櫃
    ]
    for lo, hi in otc_ranges:
        if lo <= code <= hi:
            return f"{symbol}.TWO"
    return f"{symbol}.TW"


def fetch_price_data(symbol: str, period: str = "6mo") -> Optional[pd.DataFrame]:
    """
    使用 yfinance 抓取個股 OHLCV 資料。
    回傳 DataFrame 欄位：Open, High, Low, Close, Volume（張）。
    """
    yf_symbol = symbol_to_yf(symbol)
    cache_dir = Path(CONFIG["cache_dir"])
    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_file = cache_dir / f"{symbol}_{period}.csv"

    # 嘗試讀取當日快取
    today = dt.date.today().isoformat()
    if cache_file.exists():
        df_cached = pd.read_csv(cache_file, index_col=0, parse_dates=True)
        if len(df_cached) > 0 and df_cached.index[-1].date().isoformat() == today:
            return df_cached

    try:
        ticker = yf.Ticker(yf_symbol)
        df = ticker.history(period=period)
        if df.empty or len(df) < 60:
            return None

        # yfinance Volume 單位為「股」，轉為「張」（1 張 = 1000 股）
        df["Volume"] = (df["Volume"] / 1000).round(0)

        # 重新命名欄位以統一格式
        df = df.rename(columns={
            "Open": "Open", "High": "High", "Low": "Low",
            "Close": "Close", "Volume": "Volume"
        })

        # 快取
        df.to_csv(cache_file)
        time.sleep(0.3)  # 避免速率限制
        return df

    except Exception as e:
        print(f"  [警告] 無法取得 {symbol} ({yf_symbol}) 資料：{e}")
        return None


