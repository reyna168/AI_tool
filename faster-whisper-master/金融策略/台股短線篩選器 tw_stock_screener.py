def fetch_institutional_trading(date_str: str) -> Optional[pd.DataFrame]:
    """
    抓取三大法人個股買賣超（TWSE OpenAPI）。
    date_str 格式：YYYYMMDD
    """
    url = "https://www.twse.com.tw/fund/T86"
    params = {
        "response": "json",
        "date": date_str,
        "selectType": "ALLBUT0999",
    }
    try:
        resp = requests.get(url, params=params, timeout=15)
        resp.raise_for_status()
        data = resp.json()
        if data.get("stat") != "OK":
            return None

        fields = data.get("fields", [])
        records = data.get("data", [])
        if not records:
            return None

        df = pd.DataFrame(records, columns=fields)
        # 欄位名稱可能含空白，清理之
        df.columns = df.columns.str.strip()

        # 統一股票代號格式
        code_col = [c for c in df.columns if "證券" in c or "股票" in c]
        if code_col:
            df["code"] = df[code_col[0]].astype(str).str.strip()

        return df

    except Exception as e:
        print(f"  [警告] 無法取得法人資料（{date_str}）：{e}")
        return None


def get_institutional_netbuy(symbol: str, lookback_days: int = 5) -> Optional[dict]:
    """
    取得個股近 N 日三大法人買賣超摘要。
    回傳 dict: {date: {foreign: float, trust: float, dealer: float, total: float}}
    單位：張
    """
    result = {}
    today = dt.date.today()

    for i in range(lookback_days + 2):  # 多抓幾天以防休市
        d = today - dt.timedelta(days=i)
        if d.weekday() >= 5:  # 跳過週末
            continue
        date_str = d.strftime("%Y%m%d")

        df = fetch_institutional_trading(date_str)
        if df is None:
            continue

        # 找到對應股票
        matched = df[df["code"] == symbol] if "code" in df.columns else pd.DataFrame()
        if matched.empty:
            # 嘗試去掉前綴零
            matched = df[df["code"].str.lstrip("0") == symbol.lstrip("0")] if "code" in df.columns else pd.DataFrame()

        if not matched.empty:
            row = matched.iloc[0]
            # TWSE 欄位名稱可能因版本不同而異，嘗試常見欄位
            def safe_parse(val):
                if isinstance(val, str):
                    val = val.replace(",", "").replace(" ", "")
                    try:
                        return float(val)
                    except ValueError:
                        return 0.0
                return float(val) if val else 0.0

            # 找外資、投信、自營商買賣超欄位
            foreign_col = [c for c in df.columns if "外資" in c and "賣超" not in c and "買超" not in c]
            trust_col = [c for c in df.columns if "投信" in c and "賣超" not in c and "買超" not in c]
            dealer_col = [c for c in df.columns if "自營" in c and "賣超" not in c and "買超" not in c]

            # 嘗試找「買賣超」淨額欄位
            foreign_net = [c for c in df.columns if "外資" in c and ("買賣超" in c or "差額" in c)]
            trust_net = [c for c in df.columns if "投信" in c and ("買賣超" in c or "差額" in c)]
            dealer_net = [c for c in df.columns if "自營" in c and ("買賣超" in c or "差額" in c)]

            foreign_val = safe_parse(row[foreign_net[0]]) if foreign_net else 0.0
            trust_val = safe_parse(row[trust_net[0]]) if trust_net else 0.0
            dealer_val = safe_parse(row[dealer_net[0]]) if dealer_net else 0.0

            result[date_str] = {
                "foreign": foreign_val,
                "trust": trust_val,
                "dealer": dealer_val,
                "total": foreign_val + trust_val + dealer_val,
            }

        if len(result) >= lookback_days:
            break
        time.sleep(0.5)  # TWSE 速率限制

    return result if result else None


