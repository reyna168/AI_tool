def analyze_stock(symbol: str, df: pd.DataFrame,
                  enable_chip: bool = False) -> Optional[ScreenResult]:
    """分析單一股票，回傳 ScreenResult"""
    if df is None or len(df) < 60:
        return None

    result = ScreenResult(symbol=symbol)

    # --- 量價基本欄位 ---
    latest = df.iloc[-1]
    prev_close = df["Close"].iloc[-2]
    result.close = round(latest["Close"], 2)
    result.change_pct = round((latest["Close"] - prev_close) / prev_close * 100, 2)
    result.volume = round(latest["Volume"], 0)

    # --- 均量 ---
    result.avg_volume_5d = round(df["Volume"].iloc[-6:-1].mean(), 0)

    # --- 振幅 ---
    amp_series = calc_amplitude(df)
    result.amplitude = round(amp_series.iloc[-1], 2)

    # --- 均線 ---
    result.ma5 = round(calc_ma(df, CONFIG["ma_short"]).iloc[-1], 2)
    result.ma10 = round(calc_ma(df, CONFIG["ma_mid"]).iloc[-1], 2)
    result.ma20 = round(calc_ma(df, CONFIG["ma_long"]).iloc[-1], 2)
    result.ma60 = round(calc_ma(df, CONFIG["ma_extra_long"]).iloc[-1], 2)

    # --- 多頭排列 ---
    result.is_bullish_alignment = (
        result.ma5 > result.ma10 > result.ma20
    )

    # --- 創新高 ---
    lookback = CONFIG["breakout_lookback"]
    if len(df) >= lookback + 1:
        result.is_new_high_20d = latest["Close"] >= df["Close"].iloc[-(lookback+1):-1].max()

    # --- 量能激增 ---
    if result.avg_volume_5d > 0:
        vol_ratio = result.volume / result.avg_volume_5d
        result.is_volume_surge = vol_ratio >= CONFIG["volume_surge_ratio"]

    # --- 乖離率 ---
    result.bias = round(calc_bias(df, CONFIG["ma_long"]).iloc[-1], 2)

    # --- RSI ---
    rsi_series = calc_rsi(df, CONFIG["rsi_period"])
    result.rsi = round(rsi_series.iloc[-1], 2)
    result.is_rsi_oversold = result.rsi <= CONFIG["rsi_oversold"]

    # --- KD ---
    k_series, d_series = calc_kd(df, CONFIG["kd_period"])
    result.k_value = round(k_series.iloc[-1], 2)
    result.d_value = round(d_series.iloc[-1], 2)
    # KD 黃金交叉：昨日 K < D，今日 K > D
    if len(k_series) >= 2 and len(d_series) >= 2:
        result.is_kd_golden_cross = (
            k_series.iloc[-2] <= d_series.iloc[-2] and
            k_series.iloc[-1] > d_series.iloc[-1]
        )

    # --- MACD ---
    dif, macd_sig, hist = calc_macd(df, CONFIG["macd_fast"], CONFIG["macd_slow"], CONFIG["macd_signal"])
    result.macd_hist = round(hist.iloc[-1], 4)
    result.is_macd_bullish = (
        hist.iloc[-1] > 0 and hist.iloc[-1] > hist.iloc[-2]
    )

    # --- 布林通道 ---
    boll_upper, boll_mid, boll_lower = calc_bollinger(
        df, CONFIG["bollinger_period"], CONFIG["bollinger_std"]
    )
    result.is_bollinger_breakout = latest["Close"] > boll_upper.iloc[-1]

    # --- MTM ---
    mtm_series = calc_mtm(df, CONFIG["mtm_period"])
    result.is_mtm_positive = mtm_series.iloc[-1] > 0

    # --- OBV ---
    obv_series = calc_obv(df)
    obv_ma = obv_series.rolling(window=CONFIG["obv_ma_period"]).mean()
    if len(obv_series) >= 2 and not obv_ma.iloc[-2:].isna().any():
        result.is_obv_breakout = (
            obv_series.iloc[-2] <= obv_ma.iloc[-2] and
            obv_series.iloc[-1] > obv_ma.iloc[-1]
        )

    # --- 籌碼面（可選） ---
    if enable_chip:
        chip_data = get_institutional_netbuy(symbol, CONFIG["chip_lookback_days"])
        if chip_data:
            trust_buy_count = 0
            sync_buy_count = 0
            for date_str, vals in chip_data.items():
                if vals["trust"] > 0:
                    trust_buy_count += 1
                if vals["foreign"] > 0 and vals["trust"] > 0:
                    sync_buy_count += 1
                result.foreign_netbuy += vals["foreign"]
                result.trust_netbuy += vals["trust"]

            result.trust_buy_days = trust_buy_count
            result.is_inst_sync_buy = sync_buy_count >= CONFIG["chip_lookback_days"]

    return result


def screen_momentum_breakout(result: ScreenResult) -> tuple[bool, float, list]:
    """
    策略一：動能突破型（順勢做多）
    條件：
      1. 5 日均量 ≥ 門檻
      2. 5MA > 10MA > 20MA（多頭排列）
      3. 股價創近 20 日新高
      4. 當日量 > 5 日均量 × 倍數
      5. KD 黃金交叉 或 RSI 由低檔回升
      6.（可選）外資 + 投信同步買超
    """
    reasons = []
    score = 0.0

    # 條件 1：流動性
    if result.avg_volume_5d >= CONFIG["min_avg_volume_5d"]:
        reasons.append(f"5日均量 {result.avg_volume_5d:.0f}張 ≥ {CONFIG['min_avg_volume_5d']}張")
        score += 10
    else:
        return False, 0, []

    # 條件 2：多頭排列
    if result.is_bullish_alignment:
        reasons.append(f"多頭排列 5MA({result.ma5}) > 10MA({result.ma10}) > 20MA({result.ma20})")
        score += 15

    # 條件 3：創新高
    if result.is_new_high_20d:
        reasons.append(f"創近{CONFIG['breakout_lookback']}日新高")
        score += 15

    # 條件 4：量能激增
    if result.is_volume_surge:
        ratio = result.volume / result.avg_volume_5d if result.avg_volume_5d > 0 else 0
        reasons.append(f"量能激增 {result.volume:.0f}張 / 5日均量 {result.avg_volume_5d:.0f}張 = {ratio:.1f}倍")
        score += 15

    # 條件 5：技術指標確認（任一即可加分）
    tech_signals = []
    if result.is_kd_golden_cross:
        tech_signals.append("KD黃金交叉")
        score += 10
    if result.is_macd_bullish:
        tech_signals.append("MACD柱狀體由綠翻紅")
        score += 10
    if result.is_mtm_positive:
        tech_signals.append("MTM動量為正")
        score += 5
    if result.is_obv_breakout:
        tech_signals.append("OBV突破20日均線")
        score += 5
    if tech_signals:
        reasons.append("技術確認：" + "、".join(tech_signals))

    # 條件 6（可選）：法人同步買超
    if result.is_inst_sync_buy:
        reasons.append(f"外資+投信近{CONFIG['chip_lookback_days']}日同步買超")
        score += 20

    # 至少滿足條件 1+2+3 或 1+2+4 才算通過
    passed = (result.is_bullish_alignment and
              (result.is_new_high_20d or result.is_volume_surge) and
              score >= 40)

    if passed:
        result.strategy = "動能突破型"

    return passed, score, reasons


def screen_pullback_rebound(result: ScreenResult) -> tuple[bool, float, list]:
    """
    策略二：超賣反彈型（逆勢搶短）
    條件：
      1. 5 日均量 ≥ 門檻（要求更高流動性）
      2. 與 20MA 負乖離率 < 門檻
      3. RSI < 超賣區
      4. KD 在低檔區（K < 20）
      5. 出現止跌訊號（當日紅 K：收盤 > 開盤）
    """
    reasons = []
    score = 0.0

    # 條件 1：流動性（更高門檻）
    min_vol = CONFIG["min_avg_volume_5d"] * 2
    if result.avg_volume_5d >= min_vol:
        reasons.append(f"5日均量 {result.avg_volume_5d:.0f}張 ≥ {min_vol}張（高流動性）")
        score += 10
    else:
        return False, 0, []

    # 條件 2：負乖離率
    if result.bias <= CONFIG["bias_threshold"]:
        reasons.append(f"負乖離率 {result.bias:.1f}% ≤ {CONFIG['bias_threshold']}%")
        score += 20

    # 條件 3：RSI 超賣
    if result.is_rsi_oversold:
        reasons.append(f"RSI {result.rsi:.1f} ≤ {CONFIG['rsi_oversold']}（超賣）")
        score += 20

    # 條件 4：KD 低檔
    if result.k_value <= CONFIG["kd_oversold"]:
        reasons.append(f"K值 {result.k_value:.1f} ≤ {CONFIG['kd_oversold']}（低檔）")
        score += 15

    # 條件 5：止跌訊號（紅 K）
    # 注意：此處需 df 原始資料，暫用 change_pct > 0 替代
    if result.change_pct > 0:
        reasons.append(f"當日上漲 {result.change_pct:.1f}%（紅K止跌訊號）")
        score += 15

    # 額外加分：KD 黃金交叉
    if result.is_kd_golden_cross:
        reasons.append("KD 低檔黃金交叉")
        score += 10

    # 額外加分：MTM 由負轉正
    if result.is_mtm_positive:
        reasons.append("MTM 動量轉正")
        score += 5

    # 至少滿足條件 2+3 或 2+4 才算通過
    passed = (
        result.bias <= CONFIG["bias_threshold"] and
        (result.is_rsi_oversold or result.k_value <= CONFIG["kd_oversold"]) and
        score >= 40
    )

    if passed:
        result.strategy = "超賣反彈型"

    return passed, score, reasons


def screen_three_factor(result: ScreenResult) -> tuple[bool, float, list]:
    """
    策略三：三面向回測型（勝率近六成）
    技術面：股價創新高 + 量創 20 日新高 + 多頭排列
    籌碼面：外資投信同步買超 + 買賣家數差連 3 天 < -30（需外部資料）
    財務面：近 1 月營收成長率 > 近 3 月平均成長率
    """
    reasons = []
    score = 0.0

    # --- 技術面 ---
    tech_pass = True
    if result.is_new_high_20d:
        reasons.append(f"技術面：創近{CONFIG['breakout_lookback']}日新高")
        score += 15
    else:
        tech_pass = False

    if result.is_volume_surge:
        reasons.append(f"技術面：量能激增（量創20日新高）")
        score += 15
    else:
        tech_pass = False

    if result.is_bullish_alignment:
        reasons.append("技術面：多頭排列")
        score += 10
    else:
        tech_pass = False

    # --- 籌碼面 ---
    chip_pass = True
    if result.is_inst_sync_buy:
        reasons.append(f"籌碼面：外資+投信同步買超")
        score += 20
    else:
        chip_pass = False
        reasons.append("籌碼面：法人同步買超未確認（需 --enable-chip）")

    # 買賣家數差需外部資料，標註為待確認
    reasons.append("籌碼面：買賣家數差連3天<-30（待外部資料確認）")

    # --- 財務面（需 twstock 或外部營收資料） ---
    reasons.append("財務面：近1月營收成長率 > 近3月平均（待外部資料確認）")
    fin_pass = None  # 標記為未確認

    # 若技術面全通過 + 籌碼面通過，視為初步通過
    passed = tech_pass and chip_pass and score >= 40

    if passed:
        result.strategy = "三面向回測型"

    return passed, score, reasons


def screen_watchlist_score(result: ScreenResult) -> tuple[bool, float, list]:
    """
    策略四：綜合評分型（不限單一策略，加總所有訊號）
    適合用來產生每日候選名單，依分數排序。
    """
    reasons = []
    score = 0.0

    # 流動性
    if result.avg_volume_5d >= CONFIG["min_avg_volume_5d"]:
        score += 5
        reasons.append(f"5日均量 {result.avg_volume_5d:.0f}張")
    else:
        return False, 0, []

    # 多頭排列
    if result.is_bullish_alignment:
        score += 10
        reasons.append("多頭排列")

    # 創新高
    if result.is_new_high_20d:
        score += 10
        reasons.append(f"創近{CONFIG['breakout_lookback']}日新高")

    # 量能激增
    if result.is_volume_surge:
        score += 10
        ratio = result.volume / result.avg_volume_5d if result.avg_volume_5d > 0 else 0
        reasons.append(f"量能激增 {ratio:.1f}倍")

    # KD
    if result.is_kd_golden_cross:
        score += 10
        reasons.append("KD黃金交叉")
    elif result.k_value <= CONFIG["kd_oversold"]:
        score += 5
        reasons.append(f"K值低檔({result.k_value:.1f})")

    # RSI
    if result.is_rsi_oversold:
        score += 8
        reasons.append(f"RSI超賣({result.rsi:.1f})")
    elif result.rsi >= CONFIG["rsi_overbought"]:
        score += 5
        reasons.append(f"RSI強勢({result.rsi:.1f})")

    # MACD
    if result.is_macd_bullish:
        score += 8
        reasons.append("MACD由綠翻紅")

    # 布林突破
    if result.is_bollinger_breakout:
        score += 8
        reasons.append("突破布林上軌")

    # MTM
    if result.is_mtm_positive:
        score += 5
        reasons.append("MTM動量為正")

    # OBV
    if result.is_obv_breakout:
        score += 5
        reasons.append("OBV突破20日均線")

    # 乖離率
    if result.bias <= CONFIG["bias_threshold"]:
        score += 8
        reasons.append(f"負乖離{result.bias:.1f}%")

    # 籌碼
    if result.is_inst_sync_buy:
        score += 15
        reasons.append("法人同步買超")
    if result.trust_buy_days >= CONFIG["investment_trust_min_days"]:
        score += 10
        reasons.append(f"投信近{result.trust_buy_days}日買超")

    passed = score >= 30
    if passed:
        result.strategy = "綜合評分型"

    return passed, score, reasons


