STRATEGY_MAP = {
    "momentum": ("動能突破型", screen_momentum_breakout),
    "rebound": ("超賣反彈型", screen_pullback_rebound),
    "three_factor": ("三面向回測型", screen_three_factor),
    "score": ("綜合評分型", screen_watchlist_score),
}


def load_watchlist(filepath: str) -> list[str]:
    """從 CSV 或文字檔載入股票代號清單"""
    path = Path(filepath)
    if not path.exists():
        print(f"找不到 watchlist 檔案：{filepath}")
        print("請建立一個 CSV 或文字檔，每行一個股票代號，例如：")
        print("  2330")
        print("  2454")
        print("  2317")
        sys.exit(1)

    # 嘗試以 CSV 讀取
    try:
        df = pd.read_csv(filepath, dtype=str)
        # 取第一欄作為股票代號
        codes = df.iloc[:, 0].dropna().str.strip().tolist()
        # 如果有第二欄，當作股票名稱
        names = {}
        if df.shape[1] >= 2:
            for _, row in df.iterrows():
                code = str(row.iloc[0]).strip()
                name = str(row.iloc[1]).strip() if pd.notna(row.iloc[1]) else ""
                names[code] = name
        return codes, names
    except Exception:
        # 退回純文字讀取
        with open(filepath, "r") as f:
            codes = [line.strip() for line in f if line.strip()]
        return codes, {}


def run_screener(watchlist: list[str], names: dict,
                 strategy_name: str, enable_chip: bool = False) -> pd.DataFrame:
    """執行篩選，回傳結果 DataFrame"""
    strategy_label, strategy_fn = STRATEGY_MAP.get(
        strategy_name, STRATEGY_MAP["score"]
    )

    print(f"\n{'='*60}")
    print(f"  台股短線篩選器 — 策略：{strategy_label}")
    print(f"  股票數量：{len(watchlist)}")
    print(f"  籌碼資料：{'開啟' if enable_chip else '關閉'}")
    print(f"{'='*60}\n")

    results = []

    for i, symbol in enumerate(watchlist, 1):
        name = names.get(symbol, "")
        print(f"  [{i}/{len(watchlist)}] 分析 {symbol} {name}...", end=" ")

        # 取得量價資料
        df = fetch_price_data(symbol, CONFIG["history_period"])
        if df is None:
            print("跳過（無資料）")
            continue

        # 分析
        result = analyze_stock(symbol, df, enable_chip=enable_chip)
        if result is None:
            print("跳過（資料不足）")
            continue

        result.name = name

        # 套用策略
        passed, score, reasons = strategy_fn(result)
        result.score = score
        result.reasons = reasons

        status = f"通過 (分數: {score:.0f})" if passed else f"未通過 (分數: {score:.0f})"
        print(status)

        if passed:
            results.append(result)

    if not results:
        print("\n  本次篩選無符合條件之個股。")
        return pd.DataFrame()

    # 轉為 DataFrame 並排序
    rows = []
    for r in results:
        rows.append({
            "股號": r.symbol,
            "名稱": r.name,
            "策略": r.strategy,
            "收盤價": r.close,
            "漲跌幅%": r.change_pct,
            "成交量(張)": r.volume,
            "5日均量(張)": r.avg_volume_5d,
            "振幅%": r.amplitude,
            "RSI": r.rsi,
            "K值": r.k_value,
            "D值": r.d_value,
            "MACD柱": r.macd_hist,
            "乖離率%": r.bias,
            "5MA": r.ma5,
            "10MA": r.ma10,
            "20MA": r.ma20,
            "60MA": r.ma60,
            "創20日新高": "✓" if r.is_new_high_20d else "",
            "多頭排列": "✓" if r.is_bullish_alignment else "",
            "量能激增": "✓" if r.is_volume_surge else "",
            "KD金叉": "✓" if r.is_kd_golden_cross else "",
            "MACD多": "✓" if r.is_macd_bullish else "",
            "布林突破": "✓" if r.is_bollinger_breakout else "",
            "外資買超(張)": round(r.foreign_netbuy, 0) if r.foreign_netbuy else "",
            "投信買超(張)": round(r.trust_netbuy, 0) if r.trust_netbuy else "",
            "投信買超天數": r.trust_buy_days if r.trust_buy_days else "",
            "法人同步買": "✓" if r.is_inst_sync_buy else "",
            "總分": r.score,
            "符合條件": "；".join(r.reasons),
        })

    df_results = pd.DataFrame(rows)
    df_results = df_results.sort_values("總分", ascending=False).reset_index(drop=True)

    return df_results


def print_results(df: pd.DataFrame):
    """格式化印出篩選結果"""
    if df.empty:
        return

    print(f"\n{'='*60}")
    print(f"  篩選結果：共 {len(df)} 檔符合條件")
    print(f"{'='*60}\n")

    # 精簡表格印出
    display_cols = ["股號", "名稱", "收盤價", "漲跌幅%", "成交量(張)", "RSI", "K值", "總分", "符合條件"]
    df_display = df[display_cols].copy()

    # 截斷符合條件欄位
    df_display["符合條件"] = df_display["符合條件"].str[:60] + "..."

    print(df_display.to_string(index=False))
    print()


def save_results(df: pd.DataFrame, output_dir: str = "output"):
    """儲存篩選結果為 CSV"""
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    today_str = dt.date.today().strftime("%Y%m%d")
    filepath = out_dir / f"shortlist_{today_str}.csv"
    df.to_csv(filepath, index=False, encoding="utf-8-sig")
    print(f"  結果已儲存至：{filepath}")


