def calc_ma(df: pd.DataFrame, period: int, col: str = "Close") -> pd.Series:
    """移動平均線"""
    return df[col].rolling(window=period, min_periods=period).mean()


def calc_rsi(df: pd.DataFrame, period: int = 14) -> pd.Series:
    """RSI（相對強弱指標）"""
    delta = df["Close"].diff()
    gain = delta.clip(lower=0)
    loss = (-delta).clip(lower=0)
    avg_gain = gain.ewm(alpha=1/period, min_periods=period).mean()
    avg_loss = loss.ewm(alpha=1/period, min_periods=period).mean()
    rs = avg_gain / avg_loss
    rsi = 100 - (100 / (1 + rs))
    return rsi


def calc_kd(df: pd.DataFrame, period: int = 9) -> tuple[pd.Series, pd.Series]:
    """KD 隨機指標，回傳 (K, D)"""
    low_min = df["Low"].rolling(window=period, min_periods=period).min()
    high_max = df["High"].rolling(window=period, min_periods=period).max()
    rsv = (df["Close"] - low_min) / (high_max - low_min) * 100
    rsv = rsv.replace([np.inf, -np.inf], np.nan).fillna(50)
    k = rsv.ewm(alpha=1/3, min_periods=period).mean()
    d = k.ewm(alpha=1/3, min_periods=period).mean()
    return k, d


def calc_macd(df: pd.DataFrame, fast: int = 12, slow: int = 26,
              signal: int = 9) -> tuple[pd.Series, pd.Series, pd.Series]:
    """MACD，回傳 (DIF, MACD_signal, histogram)"""
    ema_fast = df["Close"].ewm(span=fast, min_periods=fast).mean()
    ema_slow = df["Close"].ewm(span=slow, min_periods=slow).mean()
    dif = ema_fast - ema_slow
    macd_signal = dif.ewm(span=signal, min_periods=signal).mean()
    hist = dif - macd_signal
    return dif, macd_signal, hist


def calc_bollinger(df: pd.DataFrame, period: int = 20,
                   std_mult: float = 2.0) -> tuple[pd.Series, pd.Series, pd.Series]:
    """布林通道，回傳 (upper, middle, lower)"""
    mid = df["Close"].rolling(window=period, min_periods=period).mean()
    std = df["Close"].rolling(window=period, min_periods=period).std()
    upper = mid + std_mult * std
    lower = mid - std_mult * std
    return upper, mid, lower


def calc_mtm(df: pd.DataFrame, period: int = 10) -> pd.Series:
    """動量指標（Momentum）"""
    return df["Close"] - df["Close"].shift(period)


def calc_obv(df: pd.DataFrame) -> pd.Series:
    """OBV（能量潮）"""
    direction = np.sign(df["Close"].diff().fillna(0))
    obv = (direction * df["Volume"]).cumsum()
    return obv


def calc_atr(df: pd.DataFrame, period: int = 14) -> pd.Series:
    """ATR（平均真實波幅）"""
    high_low = df["High"] - df["Low"]
    high_close = (df["High"] - df["Close"].shift()).abs()
    low_close = (df["Low"] - df["Close"].shift()).abs()
    tr = pd.concat([high_low, high_close, low_close], axis=1).max(axis=1)
    atr = tr.rolling(window=period, min_periods=period).mean()
    return atr


def calc_bias(df: pd.DataFrame, ma_period: int = 20) -> pd.Series:
    """乖離率（%）"""
    ma = calc_ma(df, ma_period)
    return ((df["Close"] - ma) / ma * 100)


def calc_amplitude(df: pd.DataFrame) -> pd.Series:
    """振幅（%）"""
    return (df["High"] - df["Low"]) / df["Close"].shift() * 100


def calc_turnover_rate(df: pd.DataFrame, shares_outstanding: float = 0) -> pd.Series:
    """周轉率（%），需提供流通在外張數"""
    if shares_outstanding <= 0:
        return pd.Series(dtype=float, index=df.index)
    return df["Volume"] / shares_outstanding * 100


